using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Client.UserInterface.Controls;
using Content.Shared.MedicalScanner;
using Content.Shared._FarHorizons.Medical.Surgery;
using Content.Shared._FarHorizons.Medical.LimbStatusEffect;
using Robust.Shared.Prototypes;
using System.Linq;
using Content.Shared.Body;
using System.Numerics;
using Robust.Client.GameObjects;

namespace Content.Client._FarHorizons.Medical.Surgery;

[GenerateTypedNameReferences]
public sealed partial class SurgeryComputerWindow : FancyWindow
{
    private readonly IEntityManager _entMan;
    private readonly IPrototypeManager _protoMan;

    private readonly LimbStatusEffectSystem _limbStatusEffect;
    private readonly SurgerySystem _surgery;
    private readonly SpriteSystem _sprite;
    public event Action? OnBackPressed;
    
    private EntityUid? _targetEnt = null;
    private ProtoId<OrganCategoryPrototype>? _targetLimb = null;
    private SurgeryTutorialPrototype? _selectedSurgery = null;

    private static readonly StyleBoxFlat DoneStyle = new()
    {
        BackgroundColor = Color.FromHex("#1E5A2E"),
        BorderColor = Color.FromHex("#2E9A4E"),
        BorderThickness = new Thickness(1)
    };

    private static readonly StyleBoxFlat PendingStyle = new()
    {
        BackgroundColor = Color.Transparent,
        BorderColor = Color.FromHex("#555555"),
        BorderThickness = new Thickness(1)
    };

    public SurgeryComputerWindow()
    {
        RobustXamlLoader.Load(this);

        var dependencies = IoCManager.Instance!;
        _entMan = dependencies.Resolve<IEntityManager>();
        _protoMan = dependencies.Resolve<IPrototypeManager>();

        _limbStatusEffect = _entMan.System<LimbStatusEffectSystem>();
        _surgery = _entMan.System<SurgerySystem>();
        _sprite = _entMan.System<SpriteSystem>();

        HealthAnalyzer.OnLimbSelectionChanged += _ => Populate(_targetEnt);

        BackButton.OnPressed += _ =>
        {
            ShowSurgeryList();
            OnBackPressed?.Invoke();
        };

        ShowSurgeryList();
    }

    private void Populate(EntityUid? uid)
    {
        if (uid != _targetEnt ||
            HealthAnalyzer.CurTarget != _targetLimb)
        {
            ShowSurgeryList();

            var tutorials = uid == null ?
                                [] :
                                _surgery.GetAllTutorials(uid.Value, HealthAnalyzer.CurTarget);
            SetSurgeries(tutorials, uid);
        }
        else if (_selectedSurgery != null)
            RepopulateSteps(_selectedSurgery);
        
        if (uid == null)
            TargetLimbLabel.Text = Loc.GetString("surgery-computer-window-no-target");
        else
        {
            var targetLimbName = Loc.GetString($"limb-category-limb-name-{HealthAnalyzer.CurTarget.ToString().ToLower()}");
            TargetLimbLabel.Text = Loc.GetString("surgery-computer-window-target-limb", ("limb", targetLimbName));
        }

        _targetEnt = uid;
        _targetLimb = HealthAnalyzer.CurTarget;
    }

    public void SetSurgeries(IEnumerable<SurgeryTutorialPrototype> surgeries, EntityUid? targetEnt)
    {
        SurgeryList.RemoveAllChildren();

        List<SurgeryTutorialPrototype> inactive = new();

        foreach (var surgery in surgeries)
        {
            var targetLimb = targetEnt == null ?
                             null :
                             _surgery.GetTargetLimb(targetEnt.Value, HealthAnalyzer.CurTarget);
            if (targetEnt == null ||
                !surgery.Conditions.All(p => p.Validate(_entMan, _limbStatusEffect, targetEnt.Value, targetLimb, null)))
            {
                inactive.Add(surgery);
                continue;
            }

            var button = new Button { Text = surgery.Name, HorizontalExpand = true };
            button.OnPressed += _ => ShowSteps(surgery);
            SurgeryList.AddChild(button);
        }

        foreach (var surgery in inactive)
        {
            var button = new Button { Text = surgery.Name, HorizontalExpand = true, Disabled = true };
            SurgeryList.AddChild(button);
        }
    }

    public void ShowSteps(SurgeryTutorialPrototype tutorial)
    {
        ShowStepsList();

        _selectedSurgery = tutorial;

        SurgeryNameLabel.Text = tutorial.Name;
        RepopulateSteps(tutorial);
    }

    public void RepopulateSteps(SurgeryTutorialPrototype tutorial)
    {
        StepList.RemoveAllChildren();

        foreach (var step in tutorial.Steps)
        {
            var surgery = _protoMan.Index(step.Step);

            var targetLimb = _surgery.GetTargetLimb(_targetEnt!.Value, HealthAnalyzer.CurTarget);
            var done = step.ConditionComplete.All(p => p.Validate(_entMan, _limbStatusEffect, _targetEnt!.Value, targetLimb, null));

            var icon = new TextureRect
            {
                SetSize = new Vector2(32, 32),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                VerticalAlignment = VAlignment.Center,
                Margin = new Thickness(0, 0, 6, 0)
            };

            if (surgery.Icon is { } iconSpec)
                icon.Texture = _sprite.Frame0(iconSpec);

            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(6)
            };
            row.AddChild(icon);
            row.AddChild(new Label
            {
                Text = Loc.GetString(surgery.Name),
                VerticalAlignment = VAlignment.Center,
                HorizontalExpand = true,
                ClipText = true
            });

            var panel = new PanelContainer { PanelOverride = done ? DoneStyle : PendingStyle };
            panel.AddChild(row);
            StepList.AddChild(panel);
        }

        foreach (var finisher in tutorial.Finishers)
        {
            if (!_protoMan.TryIndex(finisher, out var finisherProto))
                continue;
            
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                Margin = new Thickness(6)
            };

            var button = new Button { Text = finisherProto.Name, HorizontalExpand = true };
            button.OnPressed += _ => ShowSteps(finisherProto);
            row.AddChild(button);

            var panel = new PanelContainer { PanelOverride = PendingStyle };
            panel.AddChild(row);
            StepList.AddChild(panel);
        }
    }

    public void ShowSurgeryList()
    {
        StepsView.Visible = false;
        SurgeryListView.Visible = true;
        _selectedSurgery = null;
    }

    public void ShowStepsList()
    {
        StepsView.Visible = true;
        SurgeryListView.Visible = false;
    }

    public void Populate(HealthAnalyzerUiState scannerMsg)
    {
        HealthAnalyzer.Populate(scannerMsg);

        var uid = _entMan.GetEntity(scannerMsg.TargetEntity);
        Populate(uid);
    }
    
    public void SetEntity(EntityUid uid) => 
        HealthAnalyzer.SetEntity(uid);
}