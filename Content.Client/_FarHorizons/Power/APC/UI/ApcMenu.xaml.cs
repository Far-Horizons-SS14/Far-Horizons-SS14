// Far Horizons fork of upstream Content.Client/Power/APC/UI/ApcMenu.xaml.cs, which is excluded from the build.
using Content.Client._FarHorizons.Power.SmartGrid;
using Content.Shared._FarHorizons.Power.SmartGrid;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Client.GameObjects;
using Robust.Shared.IoC;
using System;
using Content.Shared.APC;
using FancyWindow = Content.Client.UserInterface.Controls.FancyWindow;

namespace Content.Client._FarHorizons.Power.APC.UI
{
    [GenerateTypedNameReferences]
    public sealed partial class ApcMenu : FancyWindow
    {
        public event Action? OnBreaker;
        public event Action<SmartGridPriority>? OnSmartGridAvailability;
        public event Action<SmartGridPriority>? OnSmartGridBatteryAvailability;

        private readonly SmartGridAvailabilityControl _smartGridAvailability = new();
        private readonly SmartGridBatteryMeter _smartGridBatteryMeter = new();

        public ApcMenu()
        {
            IoCManager.InjectDependencies(this);
            RobustXamlLoader.Load(this);
            SmartGridAvailabilityContainer.AddChild(_smartGridAvailability);
            SmartGridBatteryMeterContainer.AddChild(_smartGridBatteryMeter);

            BreakerButton.OnPressed += _ => OnBreaker?.Invoke();
            _smartGridAvailability.OnPrioritySelected += priority => OnSmartGridAvailability?.Invoke(priority);
            _smartGridBatteryMeter.OnPrioritySelected += priority => OnSmartGridBatteryAvailability?.Invoke(priority);
        }

        public void SetEntity(EntityUid entity)
        {
            EntityView.SetEntity(entity);
        }

        public void UpdateState(BoundUserInterfaceState state)
        {
            var castState = (ApcBoundInterfaceState) state;

            BreakerButton.Pressed = castState.MainBreaker;

            if (PowerLabel != null)
            {
                if (castState.Tripped)
                {
                    PowerLabel.Text = Loc.GetString("apc-menu-power-state-label-tripped");
                }
                else
                {
                    PowerLabel.Text = Loc.GetString("apc-menu-power-state-label-text", ("power", castState.Power), ("maxLoad", castState.MaxLoad));
                }
            }

            if (ExternalPowerStateLabel != null)
            {
                switch (castState.ApcExternalPower)
                {
                    case ApcExternalPowerState.None:
                        ExternalPowerStateLabel.Text = Loc.GetString("apc-menu-power-state-none");
                        ExternalPowerStateLabel.SetOnlyStyleClass("negative");
                        break;
                    case ApcExternalPowerState.Low:
                        ExternalPowerStateLabel.Text = Loc.GetString("apc-menu-power-state-low");
                        ExternalPowerStateLabel.SetOnlyStyleClass("highlight");
                        break;
                    case ApcExternalPowerState.Good:
                        ExternalPowerStateLabel.Text = Loc.GetString("apc-menu-power-state-good");
                        ExternalPowerStateLabel.SetOnlyStyleClass("positive");
                        break;
                    default:
                        throw new ArgumentOutOfRangeException();
                }
            }

            _smartGridBatteryMeter.Update(castState.Charge, castState.SmartGrid.InputIsBatteryBacked, castState.SmartGrid);
            _smartGridAvailability.Update(castState.SmartGrid);
        }

        public void SetAccessEnabled(bool hasAccess)
        {
            if(hasAccess)
            {
                BreakerButton.Disabled = false;
                BreakerButton.ToolTip = null;
            }
            else
            {
                BreakerButton.Disabled = true;
                BreakerButton.ToolTip = Loc.GetString("apc-component-insufficient-access");
            }

            _smartGridBatteryMeter.SetAccessEnabled(hasAccess);
            _smartGridAvailability.SetAccessEnabled(hasAccess);
        }
    }
}
